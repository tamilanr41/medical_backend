export function buildReportSheet(data) {
  const title = data.report?.title || "Report";
  const name = data.branding?.name || "";
  const columns = data.columns || [];
  const body = buildReportRows(data);

  const aoa = [];
  aoa.push([name || title]);
  aoa.push([title]);
  const summary = summaryParts(data).map((part) => `${part.label}: ${part.value}`).join("    |    ");
  if (summary) aoa.push([summary]);
  aoa.push([generatedLine(data)]);
  aoa.push([]);
  const headerRow = aoa.length;
  aoa.push(columns.map((col) => col.label));
  for (const row of body) aoa.push(row);

  const cols = columns.map((col, index) => {
    const max = Math.max(
      String(col.label).length,
      ...body.map((row) => String(row[index] ?? "").length)
    );
    return { wch: Math.min(42, Math.max(10, max + 2)) };
  });

  const merges = [];
  for (let row = 0; row < headerRow; row += 1) {
    if ((aoa[row] || []).length > 0) {
      merges.push({ s: { r: row, c: 0 }, e: { r: row, c: Math.max(0, columns.length - 1) } });
    }
  }

  return { aoa, cols, merges, headerRow, columns, title, filename: reportFilename(title, "xlsx") };
}
