export function formatCell(value) {
  if (value === null || value === undefined) return "";
  return String(value);
}

export function reportFilename(title, ext) {
  const stamp = new Date().toISOString().slice(0, 19).replace(/[:T]/g, "-");
  const slug = String(title || "report").replace(/[^\w]+/g, "-").replace(/^-+|-+$/g, "");
  return `${slug || "report"}-${stamp}.${ext}`;
}

export function hospitalInitials(name) {
  const words = String(name || "").trim().split(/\s+/).filter(Boolean);
  if (words.length === 0) return "";
  if (words.length === 1) return words[0].slice(0, 2).toUpperCase();
  return `${words[0][0]}${words[1][0]}`.toUpperCase();
}

function escapeHtml(value) {
  return formatCell(value).replace(/[&<>"']/g, (ch) => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;",
  })[ch]);
}

function summaryParts(data) {
  return Array.isArray(data?.meta?.summary) ? data.meta.summary : [];
}

function generatedLine(data) {
  const at = data?.meta?.generatedAt ? new Date(data.meta.generatedAt) : new Date();
  return `Generated ${at.toLocaleString()}`;
}

export function columnWidths(columns, total) {
  const weights = columns.map((col) => COLUMN_WEIGHTS[col.key] ?? 1);
  const sum = weights.reduce((acc, weight) => acc + weight, 0) || 1;
  return weights.map((weight) => (total * weight) / sum);
}

function alignClass(column) {
  if (column.key === "gender" || column.key === "age") return "center";
  if (column.align === "right") return "right";
  return "left";
}

export function buildReportRows(data) {
  const columns = data.columns || [];
  const rows = data.rows || [];
  return rows.map((row) => columns.map((col) => formatCell(row[col.key])));
}

/* --------------------------------- PDF -------------------------------- */

const PDF_MARGIN = { top: 56, right: 28, bottom: 46, left: 28 };

async function loadAutoTable() {
  const mod = await import("jspdf-autotable");
  return mod.default || mod.autoTable;
}

function contactText(brand) {
  return [brand.phone || brand.mobile, brand.email, brand.website].filter(Boolean).join("   ·   ");
}

function infoColumns(data) {
  const filters = summaryParts(data)
    .filter((part) => part.label !== "Period")
    .map((part) => `${part.label}: ${part.value}`)
    .join("   ·   ");
  const meta = data.meta || {};

  const left = [];
  if (filters) left.push(["Filters", filters]);

  const right = [["Total records", String(meta.rowCount ?? (data.rows?.length ?? 0))]];
  right.push(["Generated", generatedLine(data).replace(/^Generated\s+/, "")]);
  if (meta.generatedBy) right.push(["Generated by", String(meta.generatedBy)]);

  return { left, right };
}

export function dateRangeText(data) {
  const { from, to } = data.meta?.range || {};
  const fmt = (iso) =>
    iso && /^\d{4}-\d{2}-\d{2}$/.test(iso) ? `${iso.slice(8, 10)}/${iso.slice(5, 7)}/${iso.slice(0, 4)}` : iso || "";
  if (from && to) return ` FROM ${fmt(from)} UPTO ${fmt(to)}`;
  if (from) return ` FROM ${fmt(from)}`;
  return "";
}

/* Centered, logo-less hospital letterhead (legacy HeaderWithoutLogo.jasper). */
function drawLetterhead(doc, data, pw) {
  const brand = data.branding || {};
  const centre = pw / 2;
  const maxW = pw - PDF_MARGIN.left - PDF_MARGIN.right;
  let y = 34;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(15);
  doc.setTextColor(...REPORT_BRAND.navy);
  doc.text(brand.name || data.report?.title || "Report", centre, y, { align: "center" });

  if (brand.address) {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(...REPORT_BRAND.ink);
    const lines = doc.splitTextToSize(brand.address, maxW);
    y += 13;
    doc.text(lines, centre, y, { align: "center", lineHeightFactor: 1.3 });
    y += (lines.length - 1) * 12;
  }

  const contact = contactText(brand);
  if (contact) {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8.5);
    doc.setTextColor(...REPORT_BRAND.muted);
    y += 13;
    doc.text(doc.splitTextToSize(contact, maxW), centre, y, { align: "center" });
  }

  const ruleY = y + 10;
  doc.setDrawColor(...REPORT_BRAND.border);
  doc.setLineWidth(1);
  doc.line(PDF_MARGIN.left, ruleY, pw - PDF_MARGIN.right, ruleY);
  return ruleY;
}

/* Centered "<REPORT NAME> FROM <date> UPTO <date>" banner with a rule below.
   Repeats on every page; the letterhead is drawn only on the first page.
   Returns the y coordinate where the table content may begin. */
function drawPageHeader(doc, data, pw, compact) {
  const baseY = compact ? 22 : drawLetterhead(doc, data, pw);
  const text = `${(data.report?.title || "Report").toUpperCase()}${dateRangeText(data)}`;
  const maxW = pw - PDF_MARGIN.left - PDF_MARGIN.right;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(compact ? 11 : 12.5);
  doc.setTextColor(...REPORT_BRAND.navy);
  const lines = doc.splitTextToSize(text, maxW);
  const titleY = baseY + (compact ? 15 : 18);
  doc.text(lines, pw / 2, titleY, { align: "center", lineHeightFactor: 1.25 });

  const ruleY = titleY + (lines.length - 1) * 14 + 8;
  doc.setDrawColor(...REPORT_BRAND.border);
  doc.setLineWidth(0.8);
  doc.line(PDF_MARGIN.left, ruleY, pw - PDF_MARGIN.right, ruleY);
  return ruleY;
}

/* Key/value block with the filters applied and the audit trail. */
function drawInfoBox(doc, data, x, y, w) {
  const { left, right } = infoColumns(data);
  const columns = [];
  if (left.length) columns.push(left);
  columns.push(right);

  const padX = 14;
  const padY = 12;
  const gap = 26;
  const colW = (w - padX * 2 - gap * (columns.length - 1)) / columns.length;
  const lineH = 13;
  const labelFont = 8;
  const valueFont = 8.5;

  const layouts = columns.map((entries, index) => {
    const cx = x + padX + index * (colW + gap);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(labelFont);
    const labelW = Math.max(0, ...entries.map(([label]) => doc.getTextWidth(`${label}:`))) + 6;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(valueFont);
    let cy = y + padY + valueFont + 1;
    const draws = [];
    for (const [label, value] of entries) {
      const lines = doc.splitTextToSize(String(value || ""), Math.max(40, colW - labelW));
      draws.push({ label, labelW, cx, cy, lines });
      cy += Math.max(1, lines.length) * lineH + 3;
    }
    return { draws, bottom: cy };
  });

  const bottom = Math.max(...layouts.map((layer) => layer.bottom));
  const height = bottom - y + padY - 4;

  doc.setFillColor(246, 248, 251);
  doc.setDrawColor(219, 227, 238);
  doc.setLineWidth(0.6);
  doc.roundedRect(x, y, w, height, 4, 4, "FD");

  for (const item of layouts.flatMap((layer) => layer.draws)) {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(labelFont);
    doc.setTextColor(...REPORT_BRAND.slate);
    doc.text(`${item.label}:`, item.cx, item.cy);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(valueFont);
    doc.setTextColor(...REPORT_BRAND.ink);
    doc.text(item.lines, item.cx + item.labelW, item.cy, { lineHeightFactor: 1.25 });
  }

  return y + height;
}

/* Row of summary total cards (New/Old cases, Expired, credit limit, ...). */
function drawStatsStrip(doc, stats, x, y, w) {
  const items = Array.isArray(stats) ? stats.filter((item) => item && item.label != null) : [];
  if (items.length === 0) return y;

  const gap = 10;
  const boxW = (w - gap * (items.length - 1)) / items.length;
  const h = 40;

  items.forEach((item, index) => {
    const bx = x + index * (boxW + gap);
    doc.setFillColor(246, 248, 251);
    doc.setDrawColor(219, 227, 238);
    doc.setLineWidth(0.6);
    doc.roundedRect(bx, y, boxW, h, 4, 4, "FD");
    doc.setFillColor(...REPORT_BRAND.navy);
    doc.roundedRect(bx, y, 3, h, 1.5, 1.5, "F");
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7.5);
    doc.setTextColor(...REPORT_BRAND.muted);
    doc.text(String(item.label).toUpperCase(), bx + 12, y + 15);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(13);
    doc.setTextColor(...REPORT_BRAND.ink);
    doc.text(String(item.value ?? ""), bx + 12, y + 31);
  });

  return y + h;
}

function drawPdfFooter(doc, pw, ph) {
  const y = ph - 34;
  doc.setDrawColor(...REPORT_BRAND.border);
  doc.setLineWidth(0.6);
  doc.line(PDF_MARGIN.left, y, pw - PDF_MARGIN.right, y);
}

export async function buildReportPdf(data) {
  const { jsPDF } = await import("jspdf");
  const autoTable = await loadAutoTable();
  const title = data.report?.title || "Report";
  const columns = data.columns || [];
  const body = buildReportRows(data);
  const head = [columns.map((col) => col.label)];

  const doc = new jsPDF({ orientation: "landscape", unit: "pt", format: "a4" });
  const pw = doc.internal.pageSize.getWidth();
  const ph = doc.internal.pageSize.getHeight();
  const printable = pw - PDF_MARGIN.left - PDF_MARGIN.right;
  const widths = columnWidths(columns, printable);

  const columnStyles = {};
  columns.forEach((col, index) => {
    const align = alignClass(col);
    columnStyles[index] = { cellWidth: widths[index], halign: align };
  });

  let cursor = drawPageHeader(doc, data, pw, false);
  cursor = drawInfoBox(doc, data, PDF_MARGIN.left, cursor + 14, printable);
  cursor = drawStatsStrip(doc, data.stats, PDF_MARGIN.left, cursor + 12, printable);
  const startY = cursor + 14;

  autoTable(doc, {
    head,
    body,
    startY,
    margin: PDF_MARGIN,
    theme: "grid",
    tableWidth: printable,
    styles: {
      font: "helvetica",
      fontSize: 9,
      cellPadding: { top: 5, right: 6, bottom: 5, left: 6 },
      overflow: "linebreak",
      lineColor: REPORT_BRAND.border,
      lineWidth: 0.5,
      textColor: REPORT_BRAND.ink,
      valign: "middle",
    },
    headStyles: {
      fillColor: REPORT_BRAND.navy,
      textColor: [255, 255, 255],
      fontStyle: "bold",
      fontSize: 9,
      lineColor: REPORT_BRAND.navy,
      lineWidth: 0.5,
    },
    alternateRowStyles: { fillColor: [246, 248, 251] },
    columnStyles,
    rowPageBreak: "avoid",
    showHead: "everyPage",
    didDrawPage: (hook) => {
      if ((hook.pageNumber || 1) > 1) drawPageHeader(doc, data, pw, true);
      drawPdfFooter(doc, pw, ph);
    },
  });

  const pageCount = doc.internal.getNumberOfPages();
  for (let page = 1; page <= pageCount; page += 1) {
    doc.setPage(page);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(...REPORT_BRAND.muted);
    doc.text(`Page ${page} of ${pageCount}`, pw / 2, ph - 22, { align: "center" });
  }
  doc.setPage(1);
  return { doc, filename: reportFilename(title, "pdf") };
}

