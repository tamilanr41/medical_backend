  const rows = data.rows || [];
  const widths = columnWidths(columns, 100);

  const colgroup = widths.map((width) => `<col style="width:${width.toFixed(2)}%">`).join("");
  const head = columns
    .map((col) => `<th class="${alignClass(col)}">${escapeHtml(col.label)}</th>`)
    .join("");
  const body = rows
    .length
    ? rows
        .map(
          (row) =>
            `<tr>${columns
              .map((col) => `<td class="${alignClass(col)}">${escapeHtml(row[col.key])}</td>`)
              .join("")}</tr>`
        )
        .join("")
    : `<tr><td class="empty" colspan="${Math.max(1, columns.length)}">No records match the selected filters.</td></tr>`;

